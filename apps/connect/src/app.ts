const ServerRow = z.object({
  id: z.string(),
  user_id: z.string(),
  name: z.string(),
  hostname: z.string(),
  platform: z.string(),
  secret_hash: z.string(),
  version: z.string().nullable(),
  nibblets: z.number(),
  routes: z.string(),
  last_seen_at: z.string().nullable(),
  linked_at: z.string(),
  tunnel_id: z.string().nullable(),
  dns_record_id: z.string().nullable(),
});
type ServerRow = z.infer<typeof ServerRow>;

const LinkRow = z.object({
  code: z.string(),
  poll_hash: z.string(),
  name: z.string(),
  hostname: z.string(),
  platform: z.string(),
  status: z.enum(["pending", "approved", "denied"]),
  user_id: z.string().nullable(),
  server_id: z.string().nullable(),
  server_secret: z.string().nullable(),
  tunnel: z.string().nullable(),
  expires_at: z.string(),
  ip: z.string().nullable().default(null),
  location: z.string().nullable().default(null),
});

/** Finishes `work` after responding, on Workers; elsewhere (tests), before. */
async function inBackground(c: Context, work: Promise<unknown>): Promise<void> {
  try {
    c.executionCtx.waitUntil(work);
  } catch {
    await work;
  }
}

/** The address a request came from, as Cloudflare saw it. */
function clientIp(c: { req: { header(name: string): string | undefined } }): string | null {
  return c.req.header("cf-connecting-ip") ?? null;
}

/** Roughly where a request came from ("Brighton, GB"), from Cloudflare's request details. */
function roughLocation(request: Request): string | null {
  const cf: unknown = Reflect.get(request, "cf");
  if (typeof cf !== "object" || cf === null) return null;
  const city = Reflect.get(cf, "city");
  const country = Reflect.get(cf, "country");
  const parts = [city, country].filter((p): p is string => typeof p === "string" && p !== "");
  return parts.length ? parts.join(", ") : null;
}

const Platform = PendingLink.shape.platform;

/** The address this service is known by: `PUBLIC_URL`, or the one the request used. */
function publicUrl(c: Context<App>): string {
  return (c.env.PUBLIC_URL || new URL(c.req.url).origin).replace(/\/+$/, "");
}

function bearer(c: Context<App>): string {
  const header = c.req.header("authorization") ?? "";
  return header.startsWith("Bearer ") ? header.slice(7).trim() : "";
}

function toServer(row: ServerRow, now = Date.now()): CentralServer {
  const routes = ServerRoutes.safeParse(JSON.parse(row.routes));
  const seen = row.last_seen_at ? Date.parse(row.last_seen_at) : null;
  return {
    id: row.id,
    name: row.name,
    hostname: row.hostname,
    platform: Platform.catch("other").parse(row.platform),
    version: row.version,
    nibblets: row.nibblets,
    routes: routes.success ? routes.data : noRoutes,
    online: seen !== null && now - seen < OFFLINE_AFTER_MS,
    lastSeenAt: row.last_seen_at,
    linkedAt: row.linked_at,
  };
}

async function removeServer(env: ConnectEnv, row: ServerRow): Promise<void> {
  await env.DB.prepare("DELETE FROM servers WHERE id = ?").bind(row.id).run();
  await deleteTunnel(env, row.tunnel_id, row.dns_record_id);
}

const VapidJwk = z
  .string()
  .transform((text, ctx) => {
    try {
      return JSON.parse(text);
    } catch {
      ctx.addIssue({ code: "custom", message: "VAPID_PRIVATE_KEY isn't JSON" });
      return z.NEVER;
    }
  })
  .pipe(
    z.object({
      kty: z.literal("EC"),
      crv: z.literal("P-256"),
      x: z.string(),
      y: z.string(),
      d: z.string(),
    }),
  );

/** The push notification key, or null when notifications aren't set up. */
function vapid(env: ConnectEnv): VapidKeys | null {
  if (!env.VAPID_PRIVATE_KEY) return null;
  const jwk = VapidJwk.safeParse(env.VAPID_PRIVATE_KEY);
  if (!jwk.success) return null;
  return { privateJwk: jwk.data, subject: env.VAPID_SUBJECT || "mailto:hello@nibblets.dev" };
}

function publicPushKey(env: ConnectEnv): string | null {
  const keys = vapid(env);
  return keys ? vapidPublicKey(keys.privateJwk) : null;
}

const PushRow = z.object({ endpoint: z.string(), p256dh: z.string(), auth: z.string() });

/** What the service worker shows. */
interface PushMessage {
  title: string;
  body: string;
  /** The page a tap opens. */
  url: string;
  tag: string;
}

/**
 * Sends to every device the person turned notifications on for, forgetting
 * any the browser says are gone.
 */
async function pushToUser(
  env: ConnectEnv,
  userId: string,
  message: PushMessage,
): Promise<{ sent: number; failed: number }> {
  const keys = vapid(env);
  if (!keys) return { sent: 0, failed: 0 };
  const { results } = await env.DB.prepare(
    "SELECT endpoint, p256dh, auth FROM push_subscriptions WHERE user_id = ?",
  )
    .bind(userId)
    .all();
  let sent = 0;
  let failed = 0;
  await Promise.all(
    results.map(async (raw) => {
      const target = PushRow.parse(raw);
      const result = await sendPush(target, message, keys).catch(() => "failed" as const);
      if (result === "sent") {
        sent++;
        await env.DB.prepare("UPDATE push_subscriptions SET last_sent_at = ? WHERE endpoint = ?")
          .bind(new Date().toISOString(), target.endpoint)
          .run();
      } else if (result === "gone") {
        await env.DB.prepare("DELETE FROM push_subscriptions WHERE endpoint = ?")
          .bind(target.endpoint)
          .run();
      } else {
        failed++;
      }
    }),
  );
  return { sent, failed };
}

/** How long an approved link waits for its server to collect it before it's undone. */
const UNCLAIMED_AFTER_MS = 15 * 60_000;

/**
 * Tidies up links that went nowhere. An approval makes the server (and its
 * tunnel) straight away, so if the server never collects it, say because it
 * restarted mid-link, the person would be left with a server that never
 * comes online. Those are removed, along with stale codes.
 */
export async function sweepLinks(env: ConnectEnv, now = Date.now()): Promise<number> {
  const cutoff = new Date(now - UNCLAIMED_AFTER_MS).toISOString();
  const { results } = await env.DB.prepare(
    "SELECT s.* FROM link_requests l JOIN servers s ON s.id = l.server_id WHERE l.status = 'approved' AND l.expires_at < ? AND s.last_seen_at IS NULL",
  )
    .bind(cutoff)
    .all();
  for (const raw of results) await removeServer(env, ServerRow.parse(raw));
  await env.DB.prepare("DELETE FROM link_requests WHERE expires_at < ?").bind(cutoff).run();
  // Desktop sign-ins nobody collected: unused, the Clerk token behind each expires by itself.
  await env.DB.prepare("DELETE FROM desktop_sign_ins WHERE expires_at < ?")
    .bind(new Date().toISOString())
    .run();
  return results.length;
}

