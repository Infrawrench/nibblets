export interface ConnectOptions {
  /** Mints a Clerk sign-in token for a person; tests stand in for Clerk. */
  signInTicket?: (env: ConnectEnv, userId: string) => Promise<string>;
}

export function createApp(options: ConnectOptions = {}) {
  const signInTicket = options.signInTicket ?? clerkSignInTicket;
  const app = new Hono<App>();

  // The central UI is served from this origin, but the desktop app and
  // servers' own pages also call it.
  app.use(
    "/v1/*",
    cors({ origin: "*", allowHeaders: ["authorization", "content-type"], maxAge: 600 }),
  );

  app.onError((err, c) => {
    console.error(
      JSON.stringify({ message: "request failed", path: c.req.path, error: err.message }),
    );
    return c.json({ error: "Something went wrong" }, 500);
  });

  /** People: a Clerk session, or the dev user on localhost. */
  const requireUser = async (c: Context<App>, next: Next) => {
    const user =
      devUser(c.env, new URL(c.req.url)) ??
      (await clerkUser(c.env, bearer(c), async (id) => {
        const row = await c.env.DB.prepare("SELECT name FROM users WHERE id = ?")
          .bind(id)
          .first<{ name: string }>();
        return row?.name ?? null;
      }));
    if (!user) return c.json({ error: "Sign in first" }, 401);
    await c.env.DB.prepare(
      "INSERT INTO users (id, name, created_at) VALUES (?, ?, ?) ON CONFLICT (id) DO UPDATE SET name = excluded.name",
    )
      .bind(user.id, user.name, new Date().toISOString())
      .run();
    c.set("user", user);
    await next();
  };

  /** Servers: their id in the path and their secret as the bearer. */
  const requireServer = async (c: Context<App>, next: Next) => {
    const id = c.req.param("id") ?? "";
    const row = await c.env.DB.prepare("SELECT secret_hash FROM servers WHERE id = ?")
      .bind(id)
      .first<{ secret_hash: string }>();
    const secret = bearer(c);
    if (!row || !secret || !sameDigest(await sha256(secret), row.secret_hash)) {
      return c.json({ error: "Not linked" }, 401);
    }
    c.set("serverId", id);
    await next();
  };

  const ownServer = async (c: Context<App>): Promise<ServerRow | null> => {
    const row = await c.env.DB.prepare("SELECT * FROM servers WHERE id = ? AND user_id = ?")
      .bind(c.req.param("id") ?? "", c.get("user").id)
      .first();
    return row ? ServerRow.parse(row) : null;
  };

  // Public

  app.get("/.well-known/jwks.json", async (c) => {
    const key = await loadSigningKey(c.env.JWT_PRIVATE_KEY);
    c.header("cache-control", "public, max-age=300");
    return c.json({ keys: [key.publicJwk] });
  });

  /** What the central UI needs before anyone has signed in. */
  app.get("/v1/config", (c) =>
    c.json({
      clerkPublishableKey: c.env.CLERK_PUBLISHABLE_KEY,
      centralUrl: publicUrl(c),
      devAuth: devUser(c.env, new URL(c.req.url)) !== null,
      vapidPublicKey: publicPushKey(c.env),
    }),
  );

  // Linking, from the server's side

  app.post("/v1/link/start", async (c) => {
    const body = LinkStartRequest.safeParse(await c.req.json().catch(() => null));
    if (!body.success) return c.json({ error: "Send { name, hostname, platform }" }, 400);
    const code = linkCode();
    const pollToken = randomToken();
    const expiresAt = new Date(Date.now() + LINK_TTL_MS).toISOString();
    await c.env.DB.batch([
      c.env.DB.prepare("DELETE FROM link_requests WHERE expires_at < ?").bind(
        new Date().toISOString(),
      ),
      c.env.DB.prepare(
        "INSERT INTO link_requests (code, poll_hash, name, hostname, platform, expires_at, created_at, ip, location) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)",
      ).bind(
        code,
        await sha256(pollToken),
        body.data.name,
        body.data.hostname,
        body.data.platform,
        expiresAt,
        new Date().toISOString(),
        clientIp(c),
        roughLocation(c.req.raw),
      ),
    ]);
    const approveUrl = `${publicUrl(c)}/link?code=${encodeURIComponent(code)}`;
    const answer: LinkStartResponse = {
      code,
      approveUrl,
      pollToken,
      expiresAt,
      intervalSeconds: POLL_INTERVAL_SECONDS,
    };
    return c.json(answer);
  });

  app.post("/v1/link/poll", async (c) => {
    const token = bearer(c);
    if (!token) return c.json({ error: "Send the poll token" }, 401);
    const raw = await c.env.DB.prepare("SELECT * FROM link_requests WHERE poll_hash = ?")
      .bind(await sha256(token))
      .first();
    const reply = (answer: LinkPollResponse) => c.json(answer);
    if (!raw) return reply({ status: "expired" });
    const link = LinkRow.parse(raw);
    if (link.status === "denied") {
      await c.env.DB.prepare("DELETE FROM link_requests WHERE code = ?").bind(link.code).run();
      return reply({ status: "denied" });
    }
    if (link.status === "pending") {
      return reply(
        Date.parse(link.expires_at) < Date.now() ? { status: "expired" } : { status: "pending" },
      );
    }
    // Approved: hand the credentials over exactly once.
    await c.env.DB.prepare("DELETE FROM link_requests WHERE code = ?").bind(link.code).run();
    const user = await c.env.DB.prepare("SELECT name FROM users WHERE id = ?")
      .bind(link.user_id ?? "")
      .first<{ name: string }>();
    const tunnel: ManagedTunnel | null = link.tunnel
      ? z.object({ token: z.string(), hostname: z.string() }).parse(JSON.parse(link.tunnel))
      : null;
    return reply({
      status: "approved",
      serverId: link.server_id ?? "",
      serverSecret: link.server_secret ?? "",
      centralUrl: publicUrl(c),
      account: user?.name ?? "your account",
      tunnel,
    });
  });

  // Linking, from the person's side

  app.get("/v1/link/:code", requireUser, async (c) => {
    const raw = await c.env.DB.prepare("SELECT * FROM link_requests WHERE code = ?")
      .bind((c.req.param("code") ?? "").toUpperCase())
      .first();
    if (!raw) return c.json({ error: "That code has expired or was already used" }, 404);
    const link = LinkRow.parse(raw);
    if (link.status !== "pending" || Date.parse(link.expires_at) < Date.now()) {
      return c.json({ error: "That code has expired or was already used" }, 404);
    }
    const pending: PendingLink = {
      code: link.code,
      name: link.name,
      hostname: link.hostname,
      platform: Platform.catch("other").parse(link.platform),
      expiresAt: link.expires_at,
      location: link.location,
      sameNetwork: link.ip !== null && link.ip === clientIp(c),
    };
    return c.json(pending);
  });

  app.post("/v1/link/:code/approve", requireUser, async (c) => {
    const code = (c.req.param("code") ?? "").toUpperCase();
    const raw = await c.env.DB.prepare(
      "SELECT * FROM link_requests WHERE code = ? AND status = 'pending'",
    )
      .bind(code)
      .first();
    if (!raw) return c.json({ error: "That code has expired or was already used" }, 404);
    const link = LinkRow.parse(raw);
    if (Date.parse(link.expires_at) < Date.now())
      return c.json({ error: "That code has expired" }, 410);
    // A link started from another network may be one someone sent: it takes
    // the person saying they started it, not just a click.
    const body = ApproveLink.safeParse(await c.req.json().catch(() => ({})));
    const sameNetwork = link.ip !== null && link.ip === clientIp(c);
    if (!sameNetwork && !(body.success && body.data.startedItMyself)) {
      return c.json(
        { error: "Confirm you started this on your own computer before connecting it" },
        409,
      );
    }

    const user = c.get("user");
    const serverId = randomId("srv");
    const secret = randomToken();
    let tunnel: { tunnelId: string; dnsRecordId: string; hostname: string; token: string } | null =
      null;
    if (tunnelsConfigured(c.env)) {
      tunnel = await createTunnel(c.env, serverId);
    }
    const now = new Date().toISOString();
    await c.env.DB.batch([
      c.env.DB.prepare(
        "INSERT INTO servers (id, user_id, name, hostname, platform, secret_hash, linked_at, tunnel_id, dns_record_id) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)",
      ).bind(
        serverId,
        user.id,
        link.name,
        link.hostname,
        link.platform,
        await sha256(secret),
        now,
        tunnel?.tunnelId ?? null,
        tunnel?.dnsRecordId ?? null,
      ),
      c.env.DB.prepare(
        "UPDATE link_requests SET status = 'approved', user_id = ?, server_id = ?, server_secret = ?, tunnel = ? WHERE code = ?",
      ).bind(
        user.id,
        serverId,
        secret,
        tunnel ? JSON.stringify({ token: tunnel.token, hostname: tunnel.hostname }) : null,
        code,
      ),
    ]);
    // Every device hears about it, so a server added by mistake is noticed.
    await inBackground(
      c,
      pushToUser(c.env, user.id, {
        title: "A server was connected to your account",
        body: `${link.name} (${link.hostname})${link.location ? ` in ${link.location}` : ""}. Not you? Remove it in Settings.`,
        url: "/settings",
        tag: `linked:${serverId}`,
      }).catch(() => undefined),
    );
    return c.json({ serverId, name: link.name });
  });

  app.post("/v1/link/:code/deny", requireUser, async (c) => {
    await c.env.DB.prepare(
      "UPDATE link_requests SET status = 'denied' WHERE code = ? AND status = 'pending'",
    )
      .bind((c.req.param("code") ?? "").toUpperCase())
      .run();
    return c.json({ ok: true });
  });

  // Servers reporting in

  app.post("/v1/servers/:id/heartbeat", requireServer, async (c) => {
    const body = HeartbeatRequest.safeParse(await c.req.json().catch(() => null));
    if (!body.success) return c.json({ error: "Bad heartbeat" }, 400);
    await c.env.DB.prepare(
      "UPDATE servers SET name = ?, version = ?, nibblets = ?, routes = ?, last_seen_at = ? WHERE id = ?",
    )
      .bind(
        body.data.name,
        body.data.version,
        body.data.nibblets,
        JSON.stringify(body.data.routes),
        new Date().toISOString(),
        c.get("serverId"),
      )
      .run();
    return c.json({ linked: true, centralUrl: publicUrl(c) });
  });

  app.post("/v1/servers/:id/unlink", requireServer, async (c) => {
    const raw = await c.env.DB.prepare("SELECT * FROM servers WHERE id = ?")
      .bind(c.get("serverId"))
      .first();
    if (raw) await removeServer(c.env, ServerRow.parse(raw));
    return c.json({ ok: true });
  });

  // Push notifications

  app.post("/v1/push/subscriptions", requireUser, async (c) => {
    if (!vapid(c.env)) return c.json({ error: "Notifications aren't set up here" }, 503);
    const body = PushSubscriptionInput.safeParse(await c.req.json().catch(() => null));
    if (!body.success) return c.json({ error: "Send a push subscription" }, 400);
    const { endpoint, keys, label } = body.data;
    await c.env.DB.prepare(
      "INSERT INTO push_subscriptions (endpoint, user_id, p256dh, auth, label, created_at) VALUES (?, ?, ?, ?, ?, ?) ON CONFLICT (endpoint) DO UPDATE SET user_id = excluded.user_id, p256dh = excluded.p256dh, auth = excluded.auth, label = excluded.label",
    )
      .bind(
        endpoint,
        c.get("user").id,
        keys.p256dh,
        keys.auth,
        label ?? null,
        new Date().toISOString(),
      )
      .run();
    return c.json({ ok: true });
  });

  app.delete("/v1/push/subscriptions", requireUser, async (c) => {
    const body = z.object({ endpoint: z.string() }).safeParse(await c.req.json().catch(() => null));
    if (!body.success) return c.json({ error: "Send { endpoint }" }, 400);
    await c.env.DB.prepare("DELETE FROM push_subscriptions WHERE endpoint = ? AND user_id = ?")
      .bind(body.data.endpoint, c.get("user").id)
      .run();
    return c.json({ ok: true });
  });

  app.post("/v1/push/test", requireUser, async (c) =>
    c.json(
      await pushToUser(c.env, c.get("user").id, {
        title: "Notifications are on",
        body: "This is how you'll hear when a nibblet needs you.",
        url: "/",
        tag: "test",
      }),
    ),
  );

  /** A server telling its owner something, like a nibblet waiting on an approval. */
  app.post("/v1/servers/:id/notify", requireServer, async (c) => {
    const note = PushNote.safeParse(await c.req.json().catch(() => null));
    if (!note.success) return c.json({ error: "Bad note" }, 400);
    const owner = await c.env.DB.prepare("SELECT user_id FROM servers WHERE id = ?")
      .bind(c.get("serverId"))
      .first<{ user_id: string }>();
    if (!owner) return c.json({ error: "Not linked" }, 401);
    const serverId = encodeURIComponent(c.get("serverId"));
    return c.json(
      await pushToUser(c.env, owner.user_id, {
        title: note.data.title,
        body: note.data.body,
        url: `/n/${serverId}/${encodeURIComponent(note.data.nibbletId)}`,
        tag: `${c.get("serverId")}:${note.data.tag}`,
      }),
    );
  });

  // The person's servers

  app.get("/v1/servers", requireUser, async (c) => {
    const { results } = await c.env.DB.prepare(
      "SELECT * FROM servers WHERE user_id = ? ORDER BY linked_at",
    )
      .bind(c.get("user").id)
      .all();
    return c.json({
      user: c.get("user"),
      servers: results.map((r) => toServer(ServerRow.parse(r))),
    });
  });

  app.patch("/v1/servers/:id", requireUser, async (c) => {
    const body = z
      .object({ name: z.string().min(1).max(80) })
      .safeParse(await c.req.json().catch(() => null));
    if (!body.success) return c.json({ error: "Send { name }" }, 400);
    const row = await ownServer(c);
    if (!row) return c.json({ error: "No such server" }, 404);
    await c.env.DB.prepare("UPDATE servers SET name = ? WHERE id = ?")
      .bind(body.data.name, row.id)
      .run();
    return c.json(toServer({ ...row, name: body.data.name }));
  });

  app.delete("/v1/servers/:id", requireUser, async (c) => {
    const row = await ownServer(c);
    if (!row) return c.json({ error: "No such server" }, 404);
    await removeServer(c.env, row);
    return c.json({ ok: true });
  });

  /** A five-minute credential the browser uses to talk to one server directly. */
  app.post("/v1/servers/:id/token", requireUser, async (c) => {
    const row = await ownServer(c);
    if (!row) return c.json({ error: "No such server" }, 404);
    const user = c.get("user");
    const minted: ServerToken = await serverToken(await loadSigningKey(c.env.JWT_PRIVATE_KEY), {
      issuer: publicUrl(c),
      serverId: row.id,
      userId: user.id,
      name: user.name,
    });
    return c.json(minted);
  });

  // Signing the desktop app in from the browser

  /**
   * The browser, signed in: leaves a sign-in for the desktop app that asked,
   * under a handle the browser passes back to the app through its own link.
   */
  app.post("/v1/desktop/sign-in", requireUser, async (c) => {
    const body = DesktopSignInStart.safeParse(await c.req.json().catch(() => null));
    if (!body.success) return c.json({ error: "Send { challenge }" }, 400);
    const ticket = await signInTicket(c.env, c.get("user").id);
    const handle = randomToken();
    const expires = new Date(Date.now() + DESKTOP_TICKET_SECONDS * 1000).toISOString();
    await c.env.DB.prepare(
      "INSERT INTO desktop_sign_ins (handle_hash, challenge, ticket, expires_at) VALUES (?, ?, ?, ?)",
    )
      .bind(await sha256(handle), body.data.challenge, ticket, expires)
      .run();
    return c.json({ handle });
  });

  /** The desktop app: collects the sign-in, once, with the secret behind the challenge. */
  app.post("/v1/desktop/sign-in/redeem", async (c) => {
    const body = DesktopSignInRedeem.safeParse(await c.req.json().catch(() => null));
    if (!body.success) return c.json({ error: "Send { handle, verifier }" }, 400);
    const row = await c.env.DB.prepare(
      "DELETE FROM desktop_sign_ins WHERE handle_hash = ? RETURNING challenge, ticket, expires_at",
    )
      .bind(await sha256(body.data.handle))
      .first<{ challenge: string; ticket: string; expires_at: string }>();
    if (
      !row ||
      row.expires_at < new Date().toISOString() ||
      !sameDigest(await sha256(body.data.verifier), row.challenge)
    ) {
      return c.json({ error: "That sign-in has expired or was already used" }, 400);
    }
    return c.json({ ticket: row.ticket });
  });

  app.all("/v1/*", (c) => c.json({ error: "Not found" }, 404));

  return app;
}
